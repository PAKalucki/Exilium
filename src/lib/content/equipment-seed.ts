import type { Item } from '../rules/model';

export type EquipmentSeed = {
  name: string;
  category: string;
  source: string;
  values: Partial<Item>;
};
// Bootstrap only: migration 4 inserts these once and never overwrites player edits.
const gear = (
  name: string,
  category: string,
  price: number,
  weight: number | null,
  notes = '',
  page = 60,
): EquipmentSeed => ({
  name,
  category,
  source: `SW PL 2015, s. ${page}`,
  values: { price, weight, notes: `SW PL 2015, s. ${page}. ${notes}`.trim() },
});
const weapon = (
  name: string,
  category: string,
  price: number,
  weight: number,
  damage: string,
  range = '',
  capacity = 0,
  notes = '',
  page = 57,
  parry = 0,
): EquipmentSeed => ({
  name,
  category,
  source: `SW PL 2015, s. ${page}`,
  values: {
    kind: 'weapon',
    price,
    weight,
    damage,
    range,
    capacity,
    parry,
    notes:
      `SW PL 2015, s. ${page}. ${notes}${capacity || category === 'Łuki i proce' ? ' Amunicję i jej koszt zapisuj osobno.' : ''}`.trim(),
  },
});
const armor = (
  name: string,
  price: number,
  weight: number,
  value: number,
  coverage: Item['coverage'],
  notes: string,
): EquipmentSeed => ({
  name,
  category: 'Pancerze i ochrona',
  source: 'SW PL 2015, s. 55',
  values: {
    kind: 'armor',
    price,
    weight,
    armor: value,
    coverage,
    notes: `SW PL 2015, s. 55. ${notes}`,
  },
});

